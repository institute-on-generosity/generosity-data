-- Research layer, part 2: a plain-English cause taxonomy over ALL NTEE codes, so any cause name a
-- researcher types maps to codes (NomBot lib/answer.ts resolves a cause the router left without a
-- code or label here). Additive: two new tables. Data dictionary: docs/research-layer.md.

-- ntee_codes: every NCCS NTEE code (etl/ntee_codes.csv): the 26 major groups (one letter) and their
-- detail codes. draft = NCCS marks the code "not for internal IRS use".
CREATE TABLE IF NOT EXISTS ntee_codes (
  code   text PRIMARY KEY,           -- 'A' (major group) or a 3-character detail code like 'A51'
  name   text NOT NULL,              -- NCCS name, e.g. 'Art Museums'
  major  char(1) GENERATED ALWAYS AS (left(code, 1)) STORED,
  draft  boolean NOT NULL DEFAULT false
);
