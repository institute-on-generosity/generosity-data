-- cause_lookup: curated terms first, then every NTEE code's own name (lowercase, '&' as 'and',
-- trailing ' n.e.c.' dropped). source tells which.
CREATE OR REPLACE VIEW cause_lookup AS
SELECT term, ntee, label, 'curated' AS source FROM cause_terms
UNION ALL
SELECT lower(regexp_replace(replace(n.name, '&', 'and'), '\s+N\.E\.C\.$', '')), ARRAY[n.code], NULL, 'ntee_name'
FROM ntee_codes n
WHERE NOT EXISTS (SELECT 1 FROM cause_terms t WHERE t.term = lower(regexp_replace(replace(n.name, '&', 'and'), '\s+N\.E\.C\.$', '')));
